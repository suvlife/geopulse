// MMSI 可能不足 9 位(如 8 位旧号),先左补零再取前三位 MID;
// 0/1/8/9 开头是岸台、SAR 飞机、便携台、航标等非船舶,没有船旗国
export function mmsiCountry(mmsi) {
  const digits = String(mmsi ?? '').replace(/\D/g, '')
  if (!digits) return '未知'
  const head = digits.padStart(9, '0').slice(0, 3)
  if (/^[0189]/.test(digits.padStart(9, '0'))) {
    // 970/972/974 是 AIS-SART / MOB / EPIRB 应急设备
    if (/^(970|972|974)/.test(digits.padStart(9, '0'))) return '应急设备'
    return '非船舶台站'
  }
  return MID_COUNTRIES[Number(head)] || '未知'
}
